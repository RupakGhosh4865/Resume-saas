def normalize_text(text: str) -> str:
    """Replace common Unicode characters that break standard PDF fonts with ASCII equivalents."""
    if not text: return ""
    replacements = {
        "\u2018": "'", "\u2019": "'",  # Smart single quotes
        "\u201c": '"', "\u201d": '"',  # Smart double quotes
        "\u2013": "-", "\u2014": "-",  # En and em dashes
        "\u2026": "...",              # Ellipses
        "\u2022": "-",                # Bullet points
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    # Fallback: remove any other non-latin1 characters to prevent crash
    return text.encode('latin-1', 'replace').decode('latin-1')

class PDFGenerator(FPDF):
    def header(self):
        # We handle header manually in content to allow dynamic positioning
        pass

    def footer(self):
        self.set_y(-15)
        self.set_font("helvetica", "I", 8)
        self.cell(0, 10, normalize_text(f"Generated by AI Resume Optimizer - Page {self.page_no()}"), align="C")

    def add_section(self, title):
        self.set_font("helvetica", "B", 12)
        self.set_fill_color(240, 240, 240)
        self.cell(0, 8, normalize_text(title.upper()), ln=True, fill=True)
        self.ln(2)

    def generate_resume_pdf(self, content):
        self.add_page()
        
        # Header - Centered
        self.set_font("helvetica", "B", 20)
        self.cell(0, 10, normalize_text(content.get("full_name", "Resume")), ln=True, align="C")
        
        self.set_font("helvetica", "", 9)
        contact = content.get("contact", {})
        contact_str = f"{contact.get('email')} | {contact.get('phone')} | {contact.get('location')}"
        self.cell(0, 5, normalize_text(contact_str), ln=True, align="C")
        
        links = []
        if contact.get("linkedin"): links.append(contact.get("linkedin"))
        if contact.get("github"): links.append(contact.get("github"))
        if links:
            self.cell(0, 5, normalize_text(" | ".join(links)), ln=True, align="C")
        
        self.ln(5)

        # Summary
        if content.get("summary"):
            self.add_section("Professional Summary")
            self.set_font("helvetica", "", 10)
            self.multi_cell(0, 5, normalize_text(content.get("summary")))
            self.ln(5)

        # Experience
        if content.get("experience"):
            self.add_section("Professional Experience")
            for exp in content.get("experience"):
                # Sequential layout to prevent horizontal space issues
                self.set_font("helvetica", "B", 10)
                role_company = f"{exp.get('role')} at {exp.get('company')}"
                self.multi_cell(0, 5, normalize_text(role_company))
                
                self.set_font("helvetica", "I", 9)
                self.cell(0, 5, normalize_text(exp.get("duration")), ln=True, align="R")
                
                self.set_font("helvetica", "", 9)
                for pt in exp.get("points", []):
                    self.multi_cell(0, 7, normalize_text(f"\u2022 {pt}"))
                self.ln(3)

        # Projects
        if content.get("projects"):
            self.add_section("Key Projects")
            for proj in content.get("projects"):
                self.set_font("helvetica", "B", 10)
                self.multi_cell(0, 5, normalize_text(f"{proj.get('title')} ({proj.get('tech')})"))
                
                self.set_font("helvetica", "", 9)
                for pt in proj.get("points", []):
                    self.multi_cell(0, 7, normalize_text(f"\u2022 {pt}"))
                self.ln(3)

        # Skills
        if content.get("skills"):
            self.add_section("Technical Skills")
            self.set_font("helvetica", "", 10)
            skills = content.get("skills", {})
            if skills.get('languages'): self.multi_cell(0, 6, normalize_text(f"Languages: {', '.join(skills.get('languages', []))}"))
            if skills.get('frameworks'): self.multi_cell(0, 6, normalize_text(f"Frameworks: {', '.join(skills.get('frameworks', []))}"))
            if skills.get('tools'): self.multi_cell(0, 6, normalize_text(f"Tools: {', '.join(skills.get('tools', []))}"))
            self.ln(5)

        # Keywords Added (for ATS impact visibility)
        if content.get("added_keywords"):
            self.add_section("Optimized Keywords")
            self.set_font("helvetica", "I", 9)
            self.multi_cell(0, 5, normalize_text(", ".join(content.get("added_keywords", []))))
            self.ln(5)

        # Education
        if content.get("education"):
            self.add_section("Education")
            for edu in content.get("education"):
                self.set_font("helvetica", "B", 10)
                self.multi_cell(0, 5, normalize_text(edu.get("institution")))
                
                self.set_font("helvetica", "I", 9)
                self.cell(0, 5, normalize_text(edu.get("duration")), ln=True, align="R")
                
                self.set_font("helvetica", "", 9)
                self.multi_cell(0, 5, normalize_text(edu.get("degree")))
                if edu.get("details"):
                    self.multi_cell(0, 5, normalize_text(edu.get("details")))
                self.ln(3)

        return self.output(dest="S")

